/**
 * Rebuilds src/data/andalucia.js — the province → municipality list the address sheet offers.
 *
 * Two sources, joined on the INE code:
 *   the Catastro's own municipality register, because Consulta_DNPLOC only accepts the spelling
 *     it uses itself (upper case, no accents: "ALCAUCIN");
 *   an INE-coded list of accented names, so the agent reads "Alcaucín" and not "ALCAUCIN".
 *
 * The result is a static file: an agent standing in front of a house has no network guarantee,
 * and 785 municipalities cost less to ship than one photo. Run `node scripts/build-andalucia.mjs`
 * when the register changes — that is roughly never.
 */
import { writeFile } from 'node:fs/promises'

const CATASTRO = 'https://ovc.catastro.meh.es/OVCServWeb/OVCWcfCallejero/COVCCallejero.svc/json/ObtenerMunicipios'
const INE_NAMES = 'https://raw.githubusercontent.com/IagoLast/pselect/master/data/municipios.json'
const UA = 'Mozilla/5.0 (compatible; immoba/1.0; real-estate field app)'

// Andalusia, in the order a Spanish list shows them. `catastro` is the query string the register wants.
const PROVINCES = [
  { code: '04', catastro: 'ALMERIA', label: 'Almería' },
  { code: '11', catastro: 'CADIZ', label: 'Cádiz' },
  { code: '14', catastro: 'CORDOBA', label: 'Córdoba' },
  { code: '18', catastro: 'GRANADA', label: 'Granada' },
  { code: '21', catastro: 'HUELVA', label: 'Huelva' },
  { code: '23', catastro: 'JAEN', label: 'Jaén' },
  { code: '29', catastro: 'MALAGA', label: 'Málaga' },
  { code: '41', catastro: 'SEVILLA', label: 'Sevilla' },
]

const titleCase = (s) =>
  s
    .toLowerCase()
    .replace(/(^|[\s(/-])([a-záéíóúñü])/g, (_, sep, c) => sep + c.toUpperCase())
    .replace(/\b(De|Del|La|Las|Los|El|Y|En)\b/g, (w) => w.toLowerCase())

async function get(url) {
  const res = await fetch(url, { headers: { 'User-Agent': UA, Accept: 'application/json' } })
  if (!res.ok) throw new Error(`${res.status} ${url}`)
  return res.json()
}

const accented = new Map((await get(INE_NAMES)).map((m) => [m.id, m.nm]))
const out = {}
for (const p of PROVINCES) {
  const payload = await get(`${CATASTRO}?Provincia=${encodeURIComponent(p.catastro)}&Municipio=`)
  const list = payload.consulta_municipieroResult?.municipiero?.muni || []
  out[p.code] = list
    .map((m) => {
      const ine = `${m.loine.cp}${String(m.loine.cm).padStart(3, '0')}`
      return { c: m.nm, l: accented.get(ine) || titleCase(m.nm) }
    })
    .sort((a, b) => a.l.localeCompare(b.l, 'es'))
  process.stderr.write(`${p.label}: ${out[p.code].length}\n`)
}

const body = `/**
 * Andalusia's provinces and municipalities, generated by scripts/build-andalucia.mjs.
 *
 * \`c\` is the name the Sede Electrónica del Catastro answers to (Consulta_DNPLOC matches it
 * exactly); \`l\` is what the agent reads. Do not edit by hand — rerun the script.
 */
export const PROVINCES = ${JSON.stringify(PROVINCES, null, 2)}

/** Default province: the agency works the Costa del Sol. */
export const DEFAULT_PROVINCE = '29'

export const MUNICIPALITIES = ${JSON.stringify(out)}

export function provinceOf(code) {
  return PROVINCES.find((p) => p.code === code) || null
}

export function municipalitiesOf(code) {
  return MUNICIPALITIES[code] || []
}

const plain = (s) =>
  String(s ?? '')
    .normalize('NFD')
    .replace(/[\\u0300-\\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()

/**
 * Match what a map provider calls a town against the register. The provider writes "Marbella"
 * or "Vélez-Málaga"; the register writes MARBELLA and VELEZ-MALAGA, so both sides are flattened
 * before comparing. A province narrows the search; without one, a name found in a single
 * province still counts, and an ambiguous one is left to the agent.
 */
export function findMunicipality(city, province) {
  const wanted = plain(city)
  if (!wanted) return null
  const inProvince = (code) => {
    const hit = municipalitiesOf(code).find((m) => plain(m.l) === wanted || plain(m.c) === wanted)
    return hit ? { province: code, municipality: hit } : null
  }
  const p = PROVINCES.find((x) => plain(x.label) === plain(province) || plain(x.catastro) === plain(province))
  if (p) {
    const hit = inProvince(p.code)
    if (hit) return hit
  }
  const all = PROVINCES.map((x) => inProvince(x.code)).filter(Boolean)
  return all.length === 1 ? all[0] : null
}
`
await writeFile(new URL('../src/data/andalucia.js', import.meta.url), body)
process.stderr.write(`written: ${Object.values(out).reduce((n, l) => n + l.length, 0)} municipalities\n`)
